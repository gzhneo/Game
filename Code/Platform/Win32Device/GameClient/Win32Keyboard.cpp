//-------------------------------------------------------------------------------------------------
Bool Win32Keyboard::getCapsState( void )
{
	return BitTest( GetKeyState( VK_CAPITAL ), 0x01 );
}

//-------------------------------------------------------------------------------------------------
void Win32Keyboard::pushEvent( UnsignedByte key, Bool down )
{
	if( key == KEY_NONE || key == KEY_LOST )
		return;

	if( m_eventCount >= EVENT_BUFFER_SIZE )
	{
		// events beyond the buffer size are dropped
		DEBUG_LOG(( "Win32Keyboard: event buffer full, key 0x%02X dropped\n", key ));
		return;
	}

	KeyEvent &e = m_events[ ( m_eventRead + m_eventCount ) % EVENT_BUFFER_SIZE ];
	e.key = key;
	e.down = down;
	e.sequence = m_nextSequence++;
	++m_eventCount;

	m_isDown[ key ] = down;
}

//-------------------------------------------------------------------------------------------------
void Win32Keyboard::addWin32Event( UINT msg, WPARAM wParam, LPARAM lParam )
{
	const Bool down = ( msg == WM_KEYDOWN || msg == WM_SYSKEYDOWN );
	if( !down && msg != WM_KEYUP && msg != WM_SYSKEYUP )
		return;
	if( !::Engine::acceptsRealKeyboard( realInputFilter() ) )
		return;

	const UnsignedByte key = keyFromMessage( wParam, lParam );
	if( key == KEY_NONE )
		return;

	if( down )
	{
		// drop Windows auto-repeat; the engine repeats keys itself (checkKeyRepeat)
		if( ( lParam & LPARAM_PREVIOUS ) || m_isDown[ key ] )
			return;

		// AltGr: Windows sends a fake left Ctrl with the same time before the right Alt. The game
		// should only see RAlt, so the fake Ctrl is dropped. Its release is dropped below because
		// LCtrl is then not considered down.
		if( key == KEY_LCTRL )
		{
			MSG next;
			if( PeekMessageW( &next, nullptr, WM_KEYFIRST, WM_KEYLAST, PM_NOREMOVE ) &&
					( next.message == WM_KEYDOWN || next.message == WM_SYSKEYDOWN ) &&
					next.time == static_cast<DWORD>( GetMessageTime() ) &&
					keyFromMessage( next.wParam, next.lParam ) == KEY_RALT )
				return;
		}

		pushEvent( key, TRUE );
		return;
	}

	// Print Screen: Windows only sends the release (the press goes to the system screenshot),
	// so synthesize the press here.
	if( key == KEY_SYSREQ && !m_isDown[ key ] )
		pushEvent( key, TRUE );

	// Drop the release of a key the game does not consider down (after a focus change, or the
	// fake AltGr Ctrl).
	if( !m_isDown[ key ] )
		return;

	pushEvent( key, FALSE );

	// With both Shift keys down, Windows does not report the release of the first one. So on
	// any Shift release, check both against the system state.
	if( key == KEY_LSHIFT || key == KEY_RSHIFT )
	{
		if( m_isDown[ KEY_LSHIFT ] && !( GetKeyState( VK_LSHIFT ) & 0x8000 ) )
			pushEvent( KEY_LSHIFT, FALSE );
		if( m_isDown[ KEY_RSHIFT ] && !( GetKeyState( VK_RSHIFT ) & 0x8000 ) )
			pushEvent( KEY_RSHIFT, FALSE );
	}
}

//-------------------------------------------------------------------------------------------------
void Win32Keyboard::releaseAllKeys( void )
{
	for( Int k = 1; k < 256; ++k )
	{
		if( m_isDown[ k ] )
			pushEvent( static_cast<UnsignedByte>( k ), FALSE );
	}
}

//-------------------------------------------------------------------------------------------------
/** Takes one event from the buffer; KEY_NONE if there is none left. */
//-------------------------------------------------------------------------------------------------
void Win32Keyboard::getKey( KeyboardIO *key )
{
	DEBUG_ASSERTCRASH( key, ( "Win32Keyboard::getKey without a target" ) );
	key->sequence = 0;
	key->key = KEY_NONE;

	if( m_eventCount == 0 )
		return;

	const KeyEvent &e = m_events[ m_eventRead ];
	m_eventRead = ( m_eventRead + 1 ) % EVENT_BUFFER_SIZE;
	--m_eventCount;

	key->key = e.key;
	key->sequence = e.sequence;
	// assignment, not a bit set: this starts the key state
	key->state = static_cast<UnsignedByte>(e.down ? KEY_STATE_DOWN : KEY_STATE_UP);
	key->status = KeyboardIO::STATUS_UNUSED;
}
