namespace
{

/// bits in the lParam of WM_KEYDOWN/WM_KEYUP
constexpr LPARAM LPARAM_EXTENDED		= 0x01000000;	///< bit 24: extended key (E0)
constexpr LPARAM LPARAM_PREVIOUS		= 0x40000000;	///< bit 30: key was already down (repeat)

UnsignedByte keyFromMessage( WPARAM wParam, LPARAM lParam )
{
	UINT scanCode = static_cast<UINT>( ( lParam >> 16 ) & 0xFF );
	Bool extended = ( lParam & LPARAM_EXTENDED ) != 0;

	// Messages without a scan code (generated by software): derive it from the virtual key;
	// MAPVK_VK_TO_VSC_EX returns extended keys with E0 in the high byte.
	if( scanCode == 0 )
	{
		UINT vsc = MapVirtualKeyW( static_cast<UINT>( wParam ), MAPVK_VK_TO_VSC_EX );
		scanCode = vsc & 0xFF;
		extended = ( ( vsc >> 8 ) & 0xFF ) == 0xE0;
		// MapVirtualKey reports Pause as an E1 sequence or 0x45 without E0, which keyFromScanCode expects.
	}

	return KeyScan::keyFromScanCode( scanCode, extended );
}

}  // namespace

//-------------------------------------------------------------------------------------------------
Win32Keyboard::Win32Keyboard( void )
{
	m_eventRead = 0;
	m_eventCount = 0;
	m_nextSequence = 1;
	memset( m_events, 0, sizeof( m_events ) );
	memset( m_isDown, 0, sizeof( m_isDown ) );

	if( GetKeyState( VK_CAPITAL ) & 0x01 )
		m_modifiers |= KEY_STATE_CAPSLOCK;
	else
		m_modifiers &= ~KEY_STATE_CAPSLOCK;

	::Engine::context().win32Keyboard = this;
}

//-------------------------------------------------------------------------------------------------
Win32Keyboard::~Win32Keyboard( void )
{
	if( TheWin32Keyboard == this )
		::Engine::context().win32Keyboard = nullptr;
}

//-------------------------------------------------------------------------------------------------
