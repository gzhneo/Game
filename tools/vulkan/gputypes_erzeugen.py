#!/usr/bin/env python3
"""Erzeugt die Aufzaehlungen von gputypes_enums.h aus den MinGW-Headern.

Die Geraeteschicht (GpuDevice) bildet die Teilmenge von Direct3D 11 nach, die der Renderkern benutzt. Ihre Aufzaehlungen
tragen das Praefix GPU_ statt D3D11_/D3D_/DXGI_ und dieselben Zahlenwerte wie das SDK, damit die D3D11-Schicht nur
durchreicht (dort prueft static_assert jeden Wert gegen das echte SDK). Dieses Skript liest die Werte aus
/usr/x86_64-w64-mingw32/include (d3d11.h, d3dcommon.h, dxgiformat.h) und schreibt
Code/Renderer/WW3D2/Common/gputypes_enums.h und d3d11device_enums.inl (static_assert je Wert) neu.

Aufruf:  python3 tools/vulkan/gputypes_erzeugen.py [--pruefen]
         --pruefen: nichts schreiben, Rueckgabewert 1, wenn die Datei vom erzeugten Stand abweicht.
"""

import os
