"""Globale Engine-Singletons (`extern T *TheX;`) in eine gemeinsame Struktur `Engine::EngineContext` ueberfuehren (TODO 43 (e)).

Was das Werkzeug macht (mit --anwenden, sonst nur Bericht):
  1. sucht alle Deklarationen `extern [const] T *TheX;` in Code/GameEngine, Code/Platform und
     den in EXTRA_DECLS genannten Einzelstellen und loescht die Zeilen,
  2. loescht die Definitionen `T *TheX = nullptr;` (und gleichartige) in den .cpp-Dateien unter Code/ (ohne Tools),
  3. schreibt Code/Core/EngineCore/Engine/EngineContext.h neu: Vorwaertsdeklarationen, die Struktur
     `EngineContext` mit einem Zeiger je Singleton und je Singleton ein Makro `#define TheX (::Engine::context().TheX)`.
Die Aufrufstellen (`TheX->...`, `TheX = ...`) bleiben unveraendert. Neu erzeugen laesst sich die Kopfdatei aus der
vorhandenen Liste (Datei `singletons_kontext.txt`, eine Zeile `Typ Name` je Singleton).

Stufe 1 (Zugriffsfunktion): steht hinter einer Zeile das Wort `lesen`, erzeugt das Werkzeug fuer diesen Singleton eine
Zugriffsfunktion `Engine::xyz()` (Name ohne `The`, erster Buchstabe klein) und das Makro `#define TheXyz (::Engine::xyz())`;
das Feld in `EngineContext` heisst dann `xyz`. Lesende Stellen bleiben unveraendert; schreiben (`TheXyz = ...`,
`initSubsystem(TheXyz, ...)`) laesst sich der Zeiger nur noch ueber `::Engine::context().xyz` -- also nur beim Besitzer,
und das prueft der Compiler.

Dateien werden bytegenau als Latin-1 gelesen und geschrieben (CP1252, CRLF bleibt).
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'Code'))
LISTE = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'singletons_kontext.txt')
KOPF = os.path.join(ROOT, 'Core', 'EngineCore', 'Engine', 'EngineContext.h')
DECL_DIRS = [os.path.join(ROOT, 'GameEngine'), os.path.join(ROOT, 'Platform')]
EXTRA_DECLS = [os.path.join(ROOT, 'Platform', 'W3DDevice', 'GameClient', 'BaseHeightMap.cpp'),
               os.path.join(ROOT, 'Platform', 'Win32Device', 'GameClient', 'Win32Mouse.cpp'),
               os.path.join(ROOT, 'App', 'WinMain.h')]
DECL = re.compile(r'^[ \t]*extern[ \t]+((?:const[ \t]+)?[A-Za-z_][\w:]*)[ \t]*\*[ \t]*(The\w+)[ \t]*;[^\r\n]*\r?\n', re.M)
SKIP = ('Tools', 'Tests')


def lesen(p):
    return open(p, 'rb').read().decode('latin-1')


def schreiben(p, t):
    open(p, 'wb').write(t.encode('latin-1'))


def quellen():
    for d, dirs, fs in os.walk(ROOT):
        rel = os.path.relpath(d, ROOT).replace('\\', '/')
        if rel.split('/')[0] in SKIP:
            dirs[:] = []
            continue
        for f in fs:
            if f.endswith(('.cpp', '.h')):
                yield os.path.join(d, f)


def sammeln():
    gefunden = {}
    dateien = []
    for d in DECL_DIRS:
        for dd, _, fs in os.walk(d):
            dateien += [os.path.join(dd, f) for f in fs if f.endswith('.h')]
    dateien += EXTRA_DECLS
    for p in dateien:
        t = lesen(p)
        for m in DECL.finditer(t):
            gefunden.setdefault(m.group(2), (m.group(1).strip(), []))[1].append(p)
    return gefunden


def zugriff(name):
    """TheArmorStore -> armorStore, TheFXListStore -> fxListStore, TheAI -> ai"""
    rest = name[3:]
    if rest.isupper():
        return rest.lower()	# TheAI -> ai
    kopf = re.match(r'[A-Z]+(?=[A-Z][a-z])|[A-Z]', rest).group(0)	# FXListStore -> fxListStore
    return kopf.lower() + rest[len(kopf):]


def liste_lesen():
    """[(Typ, Name)] und die Menge der Namen mit Zugriffsfunktion aus singletons_kontext.txt."""
    paare, lesen_ = [], set()
    for l in open(LISTE, encoding='utf-8'):
        teile = l.split()
        if not teile:
            continue
        if teile[-1] == 'lesen':
            teile = teile[:-1]
            lesen_.add(teile[-1])
        paare.append((' '.join(teile[:-1]), teile[-1]))
    return paare, lesen_


def kopf_schreiben(paare, lesen_=frozenset()):
    """paare: [(Typ, Name)] sortiert nach Name; lesen_: Namen mit Zugriffsfunktion (Stufe 1)."""
    typen = sorted({t.replace('const ', '').strip() for t, _ in paare})
    out = ['/*', '**\tCopyright (C) 2026 GZH Neo',
           '**\tPart of GZH Neo, a modified version of Command & Conquer Generals / Zero Hour',
           '**\t(Electronic Arts). Licensed under the GNU GPL v3 or later; see LICENSE.md and NOTICE.md.',
           '*/', '',
           '// All global engine singletons in one place (generated by tools/refactor/singletons_kontext.py from',
           '// tools/refactor/singletons_kontext.txt). The old names stay valid as macros, so `TheGameLogic->...` and',
           '// `TheGameLogic = ...` compile unchanged; the pointers themselves live in the current EngineContext.',
           '// A test installs its own context with Engine::ScopedContext and leaves the real one untouched.',
           '//',
           '// Some singletons are read through an access function (Engine::armorStore() and the like): their macro is',
           '// not assignable, so only the owner sets the pointer, through ::Engine::context().armorStore.', '',
           '#pragma once', '']
    alle = ''.join(lesen(q) for q in quellen())
    out += ['%s %s;' % ('struct' if re.search(r'^\s*struct\s+%s\b\s*(:[^;]*)?[\r\n]*\s*\{' % re.escape(t), alle, re.M) else 'class', t)
            for t in typen]
    out += ['', 'namespace Engine', '{', '', 'struct EngineContext', '{']
    out += ['\t%s *%s = nullptr;' % (t, zugriff(n) if n in lesen_ else n) for t, n in paare]
    out += ['};', '',
            'extern EngineContext g_defaultContext;', 'extern EngineContext * g_currentContext;', '',
            'inline EngineContext & context() { return *g_currentContext; }', '',
            '// Makes `ctx` the current context for the lifetime of the object.',
            'class ScopedContext',
            '{',
            'public:',
            '\texplicit ScopedContext(EngineContext & ctx) : m_previous(g_currentContext) { g_currentContext = &ctx; }',
            '\t~ScopedContext() { g_currentContext = m_previous; }',
            '\tScopedContext(const ScopedContext &) = delete;',
            '\tScopedContext & operator=(const ScopedContext &) = delete;',
            'private:',
            '\tEngineContext * m_previous;',
            '};', '']
    if lesen_:
        out += ['// Read access to singletons whose pointer only the owner sets.']
        out += ['inline %s *%s() { return context().%s; }' % (t, zugriff(n), zugriff(n)) for t, n in paare if n in lesen_]
        out.append('')
    out += ['}', '']
    out += [('#define %s (::Engine::%s())' % (n, zugriff(n))) if n in lesen_ else ('#define %s (::Engine::context().%s)' % (n, n))
            for _, n in paare]
    out.append('')
    schreiben(KOPF, '\r\n'.join(out))


def main():
    anwenden = '--anwenden' in sys.argv
    gefunden = sammeln()
    paare = sorted(((t, n) for n, (t, _) in gefunden.items()), key=lambda x: x[1])
    lesen_ = set()
    if os.path.exists(LISTE):
        liste, lesen_ = liste_lesen()
        if not paare:
            paare = liste
            print('keine Deklarationen mehr; Liste aus singletons_kontext.txt')
    print('%d Singletons in %d Deklarationsdateien' % (len(paare), len({p for _, ps in gefunden.values() for p in ps})))
    namen = {n for _, n in paare}
    defpat = re.compile(r'^[ \t]*(?:/\*extern\*/[ \t]*)?(?:extern[ \t]+)?(?:class[ \t]+)?(?:const[ \t]+)?(?!return\b|delete\b|throw\b)[A-Za-z_][\w:]*[ \t]*\*[ \t]*(The\w+)[ \t]*(=[^;]*)?;[^\r\n]*(?:\r?\n|\Z)', re.M)
    entfernt_decl = entfernt_def = 0
    for p in quellen():
        t = lesen(p)
        neu = t
        if p in {q for _, ps in gefunden.values() for q in ps}:
            erste = [True]

            def decl(m):
                if m.group(2) not in namen:
                    return m.group(0)
                if erste[0]:
                    erste[0] = False
                    nl = '\r\n' if m.group(0).endswith('\r\n') else '\n'
                    return '#include "Engine/EngineContext.h"' + nl
                return ''
            neu2 = DECL.sub(decl, neu)
            entfernt_decl += neu.count('\n') - neu2.count('\n') + 1
            neu = neu2
        if p.endswith('.cpp'):
            def defn(m):
                if m.group(1) in namen:
                    if m.group(2) and not re.fullmatch(r'=\s*(nullptr|NULL|0)\s*', m.group(2)):
                        print('  ANDERER STARTWERT %s: %s' % (os.path.relpath(p, ROOT), m.group(0).strip()))
                        return m.group(0)
                    return ''
                return m.group(0)
            neu2 = defpat.sub(defn, neu)
            entfernt_def += neu.count('\n') - neu2.count('\n')
            neu = neu2
        if neu != t and anwenden:
            schreiben(p, neu)
    print('%d Deklarationszeilen, %d Definitionszeilen entfernt' % (entfernt_decl, entfernt_def))
    if anwenden:
        kopf_schreiben(paare, lesen_)
        open(LISTE, 'w', encoding='utf-8', newline='\n').write(''.join('%s %s%s\n' % (t, n, ' lesen' if n in lesen_ else '')
                                                                       for t, n in paare))
        print('EngineContext.h und singletons_kontext.txt geschrieben')


if __name__ == '__main__':
    main()
