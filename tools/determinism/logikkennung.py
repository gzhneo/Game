"""Logik-Kennung aus den Referenz-CRCs der Replays (Verträglichkeit).

Zwei Stände dürfen miteinander spielen, wenn sie gleich rechnen. Ob sie das tun, halten die Referenzreplays
unter tests/replays fest: jede bewusste Änderung der Spiellogik nimmt sie neu auf. Die Kennung ist
deshalb ein Hash über die CRC-Zeilen ("Frame CRC") aller .crc-Dateien dort, samt ihrem Pfad; die übrigen
Zeilen (Grafikkarte, Worker-Zahl) hängen vom Rechner ab und zählen nicht. Das Spiel nimmt die Kennung statt
der Exe-Bytes in die Programm-Prüfsumme (GlobalData.cpp, m_exeCRC).

  python tools/determinism/logikkennung.py            schreibt Code/GameEngine/Common/LogicVersion.h
  python tools/determinism/logikkennung.py --pruefen  Rückgabe 1, wenn die Datei nicht zu den Referenzen passt

Nach dem Neuaufnehmen von Referenzreplays einmal ohne Schalter aufrufen und die Datei mit committen; der
Prüfgang (tools/gate.sh) ruft --pruefen auf.
"""
import hashlib
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
REPLAYS = os.path.join(ROOT, "tests", "replays")
HEADER = os.path.join(ROOT, "Code", "GameEngine", "Common", "LogicVersion.h")
CRC_LINE = re.compile(r"^(\d+) ([0-9A-F]{8})$")


def kennung():
    h = hashlib.sha256()
    dateien = []
    for wurzel, _, namen in os.walk(REPLAYS):
        for name in namen:
            if name.endswith(".crc"):
                dateien.append(os.path.relpath(os.path.join(wurzel, name), REPLAYS).replace(os.sep, "/"))
    zeilen = 0
    for rel in sorted(dateien):
        h.update(("file " + rel + "\n").encode("ascii"))
        with open(os.path.join(REPLAYS, rel), "r", encoding="ascii", errors="replace") as f:
            for raw in f:
                m = CRC_LINE.match(raw.strip())
                if m:
                    h.update(("%s %s\n" % (m.group(1), m.group(2))).encode("ascii"))
                    zeilen += 1
    return int(h.hexdigest()[:8], 16), len(dateien), zeilen


def inhalt(wert, dateien, zeilen):
    return (
        "/*\n"
        "**\tCopyright (C) 2026 GZH Neo\n"
        "**\tPart of GZH Neo, a modified version of Command & Conquer Generals / Zero Hour\n"
        "**\t(Electronic Arts). Licensed under the GNU GPL v3 or later; see LICENSE.md and NOTICE.md.\n"
        "*/\n"
        "\n"
        "// LogicVersion.h -- generated by tools/determinism/logikkennung.py, do not edit.\n"
        "//\n"
        "// Hash of the reference CRCs of the replays under tests/replays (%d files, %d CRC lines). It changes\n"
        "// exactly when the game logic changes on purpose (the reference replays are recorded anew), so two\n"
        "// builds with the same value compute the same game and may play together.\n"
        "\n"
        "#pragma once\n"
        "\n"
        "#ifndef _LOGICVERSION_H_\n"
        "#define _LOGICVERSION_H_\n"
        "\n"
        "static const unsigned int GZH_LOGIC_VERSION = 0x%08Xu;\n"
        "\n"
        "#endif // _LOGICVERSION_H_\n" % (dateien, zeilen, wert)
    )


def main():
    wert, dateien, zeilen = kennung()
    if dateien == 0 or zeilen == 0:
        print("keine Referenz-CRCs unter", REPLAYS)
        return 1
    soll = inhalt(wert, dateien, zeilen)
    if "--pruefen" in sys.argv[1:]:
        try:
            with open(HEADER, "r", encoding="ascii", newline="") as f:
                ist = f.read()
        except OSError:
            ist = ""
        # Git legt die Datei je nach Einstellung mit LF oder CRLF ab
        if ist.replace("\r\n", "\n") != soll:
            print("LogicVersion.h passt nicht zu den Referenz-CRCs (soll 0x%08X); "
                  "python tools/determinism/logikkennung.py aufrufen und committen" % wert)
            return 1
        print("Logik-Kennung 0x%08X aus %d Dateien, %d CRC-Zeilen" % (wert, dateien, zeilen))
        return 0
    with open(HEADER, "w", encoding="ascii", newline="") as f:
        f.write(soll)
    print("LogicVersion.h geschrieben: 0x%08X aus %d Dateien, %d CRC-Zeilen" % (wert, dateien, zeilen))
    return 0


if __name__ == "__main__":
    sys.exit(main())
